  let lang = localStorage.getItem("played-lang") || "en";
  const snapshot = {}; // key -> original English innerHTML
  const listeners = [];

  function apply() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.dataset.i18n;
      if (!(key in snapshot)) snapshot[key] = el.innerHTML;
      const next = lang === "bn" ? (BN[key] || snapshot[key]) : snapshot[key];
      if (el.innerHTML !== next) el.innerHTML = next;
      // keep glitch overlays in sync with the swapped text
      const g = el.matches("[data-text]") ? el : el.querySelector("[data-text]");
      if (g) g.dataset.text = g.textContent;
    });
    document.documentElement.lang = lang;
    const btn = document.getElementById("lang-toggle");
    if (btn) {
      btn.textContent = lang === "bn" ? "EN" : "বাংলা";
      btn.setAttribute("aria-label", lang === "bn" ? "Switch to English" : "বাংলায় দেখো");
    }
  }

  window.I18N = {
    get lang() { return lang; },
    t(key, en) { return (lang === "bn" && BN_GAME[key]) || en; },
    toggle() {
      lang = lang === "bn" ? "en" : "bn";
      localStorage.setItem("played-lang", lang);
      apply();
      listeners.forEach(fn => { try { fn(lang); } catch { /* listener error is not our problem */ } });
    },
    onChange(fn) { listeners.push(fn); },
  };

  document.addEventListener("DOMContentLoaded", () => {
    document.getElementById("lang-toggle")?.addEventListener("click", () => window.I18N.toggle());
    apply();
  });
